import { expect, test } from "@playwright/test";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
for (const width of [360, 1440]) test(`wild rate names its caller beside inline opposite-form ally ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 950 });
  const key = "pokemon-checklist-state-v5";
  const fixture = { schemaVersion: 5, species: {}, forms: {}, starred: [], starredForms: [], settings: { forms: false, mode: "photonic-prismatic", unlocks: ["sos"] } };
  await page.goto(info.project.name === "standalone-file" ? pathToFileURL(resolve("index.html")).href : "/");
  await page.evaluate(({ key, fixture }) => { localStorage.clear(); localStorage.setItem(key, JSON.stringify(fixture)); }, { key, fixture });
  await page.reload();
  await expect(page.locator("#mode-select")).toHaveValue("photonic-prismatic");
  await expect(page.locator("#mode-select")).toBeEnabled();
  await expect(page.locator("#forms-toggle")).toHaveAttribute("aria-pressed", "false");
  const area = page.locator("details.location").filter({ has: page.locator("summary .location-title").filter({ hasText: /School/ }) });
  await expect(area).toHaveCount(1);
  if (!await area.evaluate((el: HTMLDetailsElement) => el.open)) await area.locator(":scope > summary").click();
  const row = area.locator("tbody > tr").filter({ has: page.locator(".species-name .guide-pokemon-link").filter({ hasText: "Meowth (Alolan)" }) });
  await expect(row).toHaveCount(1);
  await expect(row.locator(".inline-sos")).toContainText("Meowth (Kanto)");
  const rate = row.locator(".caller-rate");
  await expect(rate).toHaveCount(1);
  expect(await rate.innerText()).toContain("Meowth (Alolan)");
  expect(await rate.innerText()).toContain("15%");
  await expect(row.locator(".inline-sos")).not.toContainText("15%");
  await row.evaluate(el => scrollBy(0, el.getBoundingClientRect().top - document.querySelector(".app-header")!.getBoundingClientRect().bottom - 16));
  await expect.poll(() => row.evaluate(el => el.getBoundingClientRect().top >= document.querySelector(".app-header")!.getBoundingClientRect().bottom)).toBe(true);
  await page.screenshot({ path: info.outputPath("caller-owned-wild-rate.png") });
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), key)).toEqual(fixture);
});
