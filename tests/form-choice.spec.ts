import { expect, test } from "@playwright/test";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const KEY = "pokemon-checklist-state-v5";
for (const width of [390, 1440]) test.describe(`form choice ${width}px`, () => {
  test.use({ viewport: { width, height: 950 }, isMobile: width === 390, hasTouch: width === 390 });
  test("ambiguous collapsed status waits for an exact form, cancel and Undo preserve siblings", async ({ page }, info) => {
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
    const fixture = { schemaVersion: 5, species: { "1": "seen", "52": "caught" }, forms: { "52:alolan": "caught", "52:kanto": "caught" }, starred: [], starredForms: [], settings: { forms: false, mode: "photonic-prismatic", unlocks: ["sos"] } };
    const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)!), KEY);
    await page.goto(info.project.name === "standalone-file" ? pathToFileURL(resolve("index.html")).href : "/");
    await page.evaluate(value => { localStorage.clear(); localStorage.setItem("pokemon-checklist-state-v5", JSON.stringify(value)); }, fixture);
    await page.reload();
    await expect(page.getByText("Your saved checklist could not be read", { exact: false })).toHaveCount(0);
    if (width === 390) await page.getByRole("button", { name: "Pokédex", exact: true }).click();
    await page.locator("#dex-search").fill("Meowth");
    const control = page.locator('.dex-row [data-action="species"][data-species="52"]');
    await expect(control).toHaveCount(1);
    await expect(control).toHaveAccessibleName(/Meowth Pokédex status: Caught/);
    expect(await read()).toEqual(fixture);
    await control.click();
    const dialog = page.getByRole("dialog", { name: "Choose regional form", exact: true });
    await expect(dialog).toBeVisible();
    expect(await read()).toEqual(fixture);
    await expect(dialog).toContainText("Meowth (Alolan)");
    await expect(dialog).toContainText("Meowth (Kanto)");
    const box = await dialog.boundingBox();
    expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(width + 1);
    expect(box!.y).toBeGreaterThanOrEqual(0); expect(box!.y + box!.height).toBeLessThanOrEqual(951);
    await dialog.getByRole("button", { name: "Cancel", exact: true }).focus();
    await page.keyboard.press("Tab");
    expect(await dialog.evaluate(node => node.contains(document.activeElement))).toBe(true);
    await page.keyboard.press("Shift+Tab");
    expect(await dialog.evaluate(node => node.contains(document.activeElement))).toBe(true);
    await page.screenshot({ path: info.outputPath(`form-choice-${width}.png`) });
    await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await expect(control).toBeFocused();
    expect(await read()).toEqual(fixture);
    await control.click();
    await expect(dialog).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(dialog).not.toBeVisible();
    if (width === 390) await expect(page.locator(".pokedex")).toHaveClass(/drawer-open/);
    expect(await read()).toEqual(fixture);
    await control.click();
    await dialog.getByRole("button", { name: "Mark Meowth (Kanto) as Seen", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    expect(await read()).toEqual({ ...fixture, forms: { ...fixture.forms, "52:kanto": "seen" } });
    await expect(control).toHaveAccessibleName(/status: Caught/);
    if (width === 390) await page.keyboard.press("Escape");
    await expect(page.locator("#notice")).toContainText(/another form is still owned/i);
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    expect(await read()).toEqual(fixture);
    await page.locator("#header-settings-toggle").click();
    await page.getByRole("button", { name: "Close settings", exact: true }).click();
    await page.getByRole("button", { name: "Tools", exact: true }).click();
    await expect(page.locator("#tools-panel")).toBeVisible();
    await page.getByRole("button", { name: "Close tools", exact: true }).click();
    await expect(page.locator("#tools-panel")).not.toBeVisible();
    expect(await page.evaluate(() => getComputedStyle(document.body).overflow)).not.toBe("hidden");
    expect(await read()).toEqual(fixture);
    expect(errors).toEqual([]);
  });
  test("collapsed unstar chooses only one favorite and Undo restores both", async ({ page }, info) => {
    const fixture = { schemaVersion: 5, species: { "52": "caught" }, forms: { "52:alolan": "caught", "52:kanto": "caught" }, starred: [], starredForms: ["52:alolan", "52:kanto"], settings: { forms: false, mode: "photonic-prismatic", unlocks: [] } };
    const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)!), KEY);
    await page.goto(info.project.name === "standalone-file" ? pathToFileURL(resolve("index.html")).href : "/");
    await page.evaluate(value => { localStorage.clear(); localStorage.setItem("pokemon-checklist-state-v5", JSON.stringify(value)); }, fixture);
    await page.reload();
    await expect(page.getByText("Your saved checklist could not be read", { exact: false })).toHaveCount(0);
    if (width === 390) await page.getByRole("button", { name: "Pokédex", exact: true }).click();
    await page.locator("#dex-search").fill("Meowth");
    const star = page.locator('.dex-row [data-action="star"][data-species="52"]');
    await expect(star).toHaveAttribute("aria-pressed", "true");
    expect(await read()).toEqual(fixture);
    await star.click();
    const dialog = page.getByRole("dialog", { name: "Choose regional form", exact: true });
    await expect(dialog).toBeVisible();
    expect(await read()).toEqual(fixture);
    await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
    expect(await read()).toEqual(fixture);
    await star.click();
    await dialog.getByRole("button", { name: "Unstar Meowth (Kanto)", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    expect(await read()).toEqual({ ...fixture, starredForms: ["52:alolan"] });
    await expect(star).toHaveAttribute("aria-pressed", "true");
    if (width === 390) await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    expect(await read()).toEqual(fixture);
  });
  for (const owned of [true, false]) test(`resolves visible legacy favorite without assigning ownership (owned=${owned})`, async ({ page }, info) => {
    const fixture = { schemaVersion: 5, species: owned ? { "52": "caught" } : {}, forms: owned ? { "52:alolan": "caught", "52:kanto": "caught" } : {}, starred: [52], starredForms: [], settings: { forms: true, mode: "photonic-prismatic", unlocks: [] } };
    const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)!), KEY);
    await page.goto(info.project.name === "standalone-file" ? pathToFileURL(resolve("index.html")).href : "/");
    await page.evaluate(value => { localStorage.clear(); localStorage.setItem("pokemon-checklist-state-v5", JSON.stringify(value)); }, fixture);
    await page.reload();
    await expect(page.getByText("Your saved checklist could not be read", { exact: false })).toHaveCount(0);
    if (width === 390) await page.getByRole("button", { name: "Pokédex", exact: true }).click();
    await page.locator("#dex-search").fill("Meowth");
    await page.locator('.dex-row[data-target="52:kanto"] .dex-select').click();
    expect(await read()).toEqual(fixture);
    await page.getByRole("button", { name: "Choose form for existing favorite", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Choose regional form", exact: true });
    await expect(dialog).toBeVisible();
    expect(await read()).toEqual(fixture);
    await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
    expect(await read()).toEqual(fixture);
    if (owned) {
      if (width === 390) { await page.keyboard.press("Escape"); await page.locator("#header-settings-toggle").click(); }
      await page.locator("#forms-toggle").click();
      if (width === 390) {
        await page.getByRole("button", { name: "Close settings", exact: true }).click();
        await page.getByRole("button", { name: "Pokédex", exact: true }).click();
      }
      await page.locator('.dex-row [data-action="species"][data-species="52"]').click();
      await expect(dialog).toBeVisible();
      await expect(dialog.getByText(/then unstar that form/)).toHaveCount(0);
      await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
      if (width === 390) { await page.keyboard.press("Escape"); await page.locator("#header-settings-toggle").click(); }
      await page.locator("#forms-toggle").click();
      if (width === 390) {
        await page.getByRole("button", { name: "Close settings", exact: true }).click();
        await page.getByRole("button", { name: "Pokédex", exact: true }).click();
      }
      expect(await read()).toEqual(fixture);
    }
    await page.getByRole("button", { name: "Choose form for existing favorite", exact: true }).click();
    await dialog.getByRole("button", { name: "Star Meowth (Kanto)", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const expected = { ...fixture, starred: [], starredForms: ["52:kanto"] };
    expect(await read()).toEqual(expected);
    await expect(page.locator('.dex-row[data-target="52:kanto"] .star-button')).toHaveAttribute("aria-pressed", "true");
    await expect(page.locator('.dex-row[data-target="52:alolan"] .star-button')).toHaveAttribute("aria-pressed", "false");
    if (width === 390) await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    expect(await read()).toEqual(fixture);
  });
  for (const eventKind of ["remote", "tracking", "mode", "readonly"]) test(`invalidates a pending choice after ${eventKind} change`, async ({ page }, info) => {
    const fixture = { schemaVersion: 5, species: { "52": "caught" }, forms: { "52:alolan": "caught", "52:kanto": "caught" }, starred: [], starredForms: [], settings: { forms: false, mode: "photonic-prismatic", unlocks: [] } };
    await page.goto(info.project.name === "standalone-file" ? pathToFileURL(resolve("index.html")).href : "/");
    await page.evaluate(value => { localStorage.clear(); localStorage.setItem("pokemon-checklist-state-v5", JSON.stringify(value)); }, fixture);
    await page.reload();
    await expect(page.getByText("Your saved checklist could not be read", { exact: false })).toHaveCount(0);
    if (width === 390) await page.getByRole("button", { name: "Pokédex", exact: true }).click();
    await page.locator("#dex-search").fill("Meowth");
    await page.locator('.dex-row [data-action="species"][data-species="52"]').click();
    const dialog = page.getByRole("dialog", { name: "Choose regional form", exact: true });
    await expect(dialog).toBeVisible();
    const expected = structuredClone(fixture);
    if (eventKind === "remote") expected.forms["52:kanto"] = "seen";
    if (eventKind === "tracking") expected.settings.forms = true;
    if (eventKind === "mode") expected.settings.mode = "ultra-moon";
    await page.evaluate(({ value, kind }) => {
      const key = kind === "readonly" ? "pokemon-checklist-build" : "pokemon-checklist-state-v5";
      const newValue = JSON.stringify(kind === "readonly" ? { build: "synthetic-newer-build", at: Date.now() } : value);
      localStorage.setItem(key, newValue);
      window.dispatchEvent(new StorageEvent("storage", { key, newValue }));
    }, { value: expected, kind: eventKind });
    await expect(dialog).not.toBeVisible();
    expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), KEY)).toEqual(expected);
    if (width === 390) await expect(page.locator(".pokedex")).toHaveClass(/drawer-open/);
  });
  test("account namespace switch closes the pending choice without a stale write", async ({ page }, info) => {
    test.skip(info.project.name !== "vite-dev", "Dev-module account transition; pure controller tests cover the same compiled path without authentication.");
    const fixture = { schemaVersion: 5, species: { "52": "caught" }, forms: { "52:alolan": "caught", "52:kanto": "caught" }, starred: [], starredForms: [], settings: { forms: false, mode: "photonic-prismatic", unlocks: [] } };
    await page.goto("/");
    await page.evaluate(value => { localStorage.clear(); localStorage.setItem("pokemon-checklist-state-v5", JSON.stringify(value)); }, fixture);
    await page.reload();
    await expect(page.getByText("Your saved checklist could not be read", { exact: false })).toHaveCount(0);
    if (width === 390) await page.getByRole("button", { name: "Pokédex", exact: true }).click();
    await page.locator("#dex-search").fill("Meowth");
    await page.locator('.dex-row [data-action="species"][data-species="52"]').click();
    const dialog = page.getByRole("dialog", { name: "Choose regional form", exact: true });
    await expect(dialog).toBeVisible();
    await page.evaluate(async () => {
      const path = "/state.ts";
      const state = await import(path);
      state.setSyncAccount("synthetic-dialog-browser-account", { adopt: false });
    });
    await expect(dialog).not.toBeVisible();
    expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), KEY)).toEqual(fixture);
    const adopted = await page.evaluate(() => JSON.parse(localStorage.getItem("pokemon-checklist-state-v5:synthetic-dialog-browser-account")!));
    expect(adopted.forms).toEqual({}); expect(adopted.species).toEqual({});
  });
});
